import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";
import {planAdaptiveIntake} from "./adaptiveIntakePlanner_v1.mjs";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"../..");
const bank=JSON.parse(fs.readFileSync(path.join(root,"data/questions/question_bank_master.json"),"utf8")).questions;
const run=(answers={},extra={})=>planAdaptiveIntake({questionBank:bank,answers,...extra});
const first=run();
assert.equal(first.nextQuestionId,"goals_primary");
assert.equal(first.readyForPersonalization,false);
assert.ok(first.safetyMissing.includes("profile_pregnancy"));
assert.ok(first.safetyMissing.includes("medications_regular_use"));
assert.ok(!first.stages.find(s=>s.id==="context").questionIds.includes("diet_fatty_fish_weekly"));
assert.ok(run({}, {candidateQuestionIds:["diet_fatty_fish_weekly"]}).stages.find(s=>s.id==="context").questionIds.includes("diet_fatty_fish_weekly"));
assert.ok(run({medications_regular_use:"yes"}).followupQuestionIds.includes("medications_list"));
assert.ok(!run({medications_regular_use:"no"}).followupQuestionIds.includes("medications_list"));
assert.ok(run({supplements_current_use:"yes"}).followupQuestionIds.includes("supplements_current_list"));
assert.ok(run({conditions_allergies:"yes"}).followupQuestionIds.includes("conditions_allergies_list"));
assert.ok(run({medications_regular_use:"no",medications_list:["warfarin"]}).conflicts.includes("MEDICATION_LIST_CONTRADICTS_NO"));
assert.ok(run({supplements_current_use:"no",supplements_current_list:["zinc"]}).conflicts.includes("SUPPLEMENT_LIST_CONTRADICTS_NO"));
assert.ok(run({medications_regular_use:"yes"}).conflicts.includes("MEDICATION_IDENTITY_NOT_CAPTURED"));
assert.equal(run({profile_pregnancy:"unknown"}).readyForPersonalization,false);
console.log("13 adaptive intake planner assertions passed");
