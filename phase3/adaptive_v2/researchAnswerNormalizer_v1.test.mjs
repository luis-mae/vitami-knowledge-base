import assert from "node:assert/strict";
import {buildResearchRuleAnswers as normalize} from "./researchAnswerNormalizer_v1.mjs";
import {evaluateVitamiResearchScenario as evaluate} from "./researchScenarioOrchestrator_v1.mjs";
const caffeineRule={rule_id:"CAFF_HIGH_BASELINE",supplement_id:"caffeine_performance",conditions:{all:[["lifestyle_caffeine_daily",">=300mg"]],any:[]},effect:{score_delta:-4},safety_review:{clinical_approval:false}};
const raw={lifestyle_caffeine_daily:"4plus"};
const categorical=normalize(raw);
assert.ok(categorical.issues.includes("CAFFEINE_MG_NOT_ESTABLISHED"));
assert.equal(categorical.answers.lifestyle_caffeine_daily,undefined);
assert.equal(raw.lifestyle_caffeine_daily,"4plus");
const numeric=normalize({...raw,lifestyle_caffeine_mg_estimate:350});
assert.equal(numeric.answers.lifestyle_caffeine_daily,350);
assert.equal(normalize({...raw,lifestyle_caffeine_mg_estimate:"unknown"}).answers.lifestyle_caffeine_daily,undefined);
assert.ok(normalize({...raw,lifestyle_caffeine_mg_estimate:"999999"}).issues.includes("CAFFEINE_NUMERIC_INPUT_INVALID"));
const unresolved=evaluate({rules:[caffeineRule],answers:raw,medications:[],medicationListComplete:true,productLabelsComplete:true});
assert.equal(unresolved.draft.matchedRuleIds.length,0);
assert.ok(unresolved.draft.unresolved.some(x=>x.rule_id==="CAFF_HIGH_BASELINE"));
const matched=evaluate({rules:[caffeineRule],answers:{...raw,lifestyle_caffeine_mg_estimate:350},medications:[],medicationListComplete:true,productLabelsComplete:true});
assert.ok(matched.draft.matchedRuleIds.includes("CAFF_HIGH_BASELINE"));
assert.equal(matched.personalizedRecommendationAllowed,false);
console.log("9 questionnaire normalization integration assertions passed");
